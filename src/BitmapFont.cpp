BitmapFont::BitmapFont()
{
	texId = 0;
}

BitmapFont::~BitmapFont()
{
	if(texId != 0)
		glDeleteTextures(1, &texId);
}

void BitmapFont::init()
{
	const int atlasWidth = GLYPH_COUNT * GLYPH_SIZE;
	std::vector<unsigned char> atlas(atlasWidth * GLYPH_SIZE * 4, 0);
	for(int glyph = 0; glyph < GLYPH_COUNT; glyph++)
	{
		for(int row = 0; row < GLYPH_SIZE; row++)
		{
			unsigned char byte = FONT_8x8[glyph][row];
			for(int col = 0; col < GLYPH_SIZE; col++)
			{
				if((byte & (0x80 >> col)) == 0)
					continue;
				int index = (row * atlasWidth + glyph * GLYPH_SIZE + col) * 4;
				atlas[index + 0] = 255;
				atlas[index + 1] = 255;
				atlas[index + 2] = 255;
				atlas[index + 3] = 255;
			}
		}
	}

	glGenTextures(1, &texId);
	glBindTexture(GL_TEXTURE_2D, texId);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
	glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, atlasWidth, GLYPH_SIZE, 0, GL_RGBA, GL_UNSIGNED_BYTE, atlas.data());
}

void BitmapFont::use() const
{
	glBindTexture(GL_TEXTURE_2D, texId);
}

void BitmapFont::glyphCoords(char c, float &u0, float &u1) const
{
	if(c >= 'a' && c <= 'z')
		c = (char)(c - 32);
	int glyph = (c >= 32 && c <= 90) ? c - 32 : 0;
	u0 = float(glyph) / float(GLYPH_COUNT);
	u1 = float(glyph + 1) / float(GLYPH_COUNT);
}
